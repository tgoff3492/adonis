const FOODS = [...G.map(r => mk(r, 0)), ...R.map(r => mk(r, 1))];
function mk(r, rest) {
  const [name, serving, p, c, f, k, words] = r;
  return { id: (rest ? "r:" : "g:") + name.toLowerCase().replace(/[^a-z0-9]+/g, "-"), name, serving, p, c, f, k: k || 0, rest: !!rest,
    hay: norm(name + " " + (words || "")) };
}
function norm(s) { return s.toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/['’]/g, "").replace(/[^a-z0-9%]+/g, " ").trim(); }
const POP = new Set(["Chicken breast, cooked", "Egg, large", "White rice, cooked", "Banana", "Apple", "Greek yogurt, plain nonfat", "Ground beef 90/10, cooked",
  "Salmon, cooked", "Oatmeal, cooked with water", "Whole wheat bread", "Peanut butter", "Milk, 2%", "Chipotle chicken", "Potato, baked", "Avocado", "Broccoli", "Whey protein powder", "Chick-fil-A Chicken Sandwich", "Chick-fil-A Nuggets", "McDonald's Big Mac"]);
const kcal = f => f.k || Math.round(f.p * 4 + f.c * 4 + f.f * 9);

/* score: every query word must match the start of some word; earlier/whole-name matches rank higher */
function search(q, extra) {
  const words = norm(q).split(" ").filter(Boolean);
  if (!words.length) return [];
  const pool = [...(extra || []), ...FOODS];
  const out = [];
  pool.forEach(f => {
    const hayWords = (f.hay || norm(f.name)).split(" ");
    let score = 0;
    for (const w of words) {
      const i = hayWords.findIndex(h => h.startsWith(w));
      if (i < 0) { if (!(f.hay || "").includes(w) || w.length < 3) return; score += 5; }
      else score += i + (hayWords[i] === w ? 0 : 1);
    }
    if (f.mine) score -= 3;
    if (POP.has(f.name)) score -= 1.5;
    if (norm(f.name).startsWith(words.join(" "))) score -= 4;
    out.push([score + norm(f.name).length / 100, f]);
  });
  return out.sort((a, b) => a[0] - b[0]).slice(0, 25).map(x => x[1]);
}

